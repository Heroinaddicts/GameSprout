#!/usr/bin/env python3
"""Offline SDL_shadercross compilation. Generated data ships inside Runtime, no editor compiler dependency."""
import argparse
import json
import pathlib
import re
import subprocess
import tempfile


def run(arguments):
    subprocess.run([str(argument) for argument in arguments], check=True)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--shadercross", required=True, type=pathlib.Path)
    parser.add_argument("--output", type=pathlib.Path, default=pathlib.Path(__file__).with_name("GeneratedShaders.h"))
    options = parser.parse_args()
    source = pathlib.Path(__file__).with_name("Preview.hlsl")
    mapped_lit = {"LitMappedFragment": 5, "LitMappedEnvironmentFragment": 6, "LitMappedSpatialFragment": 9}
    declarations = ["// Generated by GenerateShaders.py from Preview.hlsl with SDL_shadercross. Do not hand edit.",
                    "#pragma once", "namespace GameSproutRuntime::EmbeddedShaders {"]
    with tempfile.TemporaryDirectory(prefix="gamesprout-preview-shaders-") as directory:
        root = pathlib.Path(directory)
        for entry, stage in [("MeshVertex", "vertex"), ("MeshNoUVVertex", "vertex"),
                             ("MeshNoColorVertex", "vertex"), ("MeshNoUVNoColorVertex", "vertex"),
                             ("MeshFragment", "fragment"), ("GridVertex", "vertex"), ("GridFragment", "fragment"),
                             ("SkinnedMeshVertex", "vertex"), ("SkinnedMeshNoUVVertex", "vertex"),
                             ("SkinnedMeshNoColorVertex", "vertex"), ("SkinnedMeshNoUVNoColorVertex", "vertex"),
                             ("LitFragment", "fragment"), ("LitEnvironmentFragment", "fragment"), ("LitSpatialFragment", "fragment"),
                             ("InstancedMeshVertex", "vertex"), ("InstancedMeshNoUVVertex", "vertex"),
                             ("InstancedMeshNoColorVertex", "vertex"), ("InstancedMeshNoUVNoColorVertex", "vertex"), ("ShadowFragment", "fragment"),
                             ("SkyVertex", "vertex"), ("SkyFragment", "fragment"),
                             ("CubemapSkyFragment", "fragment"),
                             ("HDRResolveVertex", "vertex"), ("HDRResolveFragment", "fragment"),
                             ("UIVertex", "vertex"), ("UIFragment", "fragment"),
                             ("ShadowVertex", "vertex"), ("InstancedShadowVertex", "vertex"),
                             ("SkinnedShadowVertex", "vertex"), ("InstancedSkinnedShadowVertex", "vertex"),
                             ("InstancedSkinnedMeshVertex", "vertex"), ("InstancedSkinnedMeshNoUVVertex", "vertex"),
                             ("InstancedSkinnedMeshNoColorVertex", "vertex"),
                             ("InstancedSkinnedMeshNoUVNoColorVertex", "vertex"),
                             *[(entry, "fragment") for entry in mapped_lit]]:
            spirv = root / (entry + ".spv")
            # One source contains several entry points. Keep only resources used
            # by that entry; retaining a fragment binding in a vertex module
            # violates SDL's stage-specific descriptor conventions.
            command = [options.shadercross, source, "-s", "HLSL", "-d", "SPIRV", "-t", stage, "-e", entry,
                       "-I", source.parent, "-c", "-o", spirv]
            if entry in mapped_lit:
                # Append the surface maps to the active fragment bindings for this entry.
                slot = mapped_lit[entry]
                command += ["-DGAMESPROUT_MAPPED_LIT",
                            f"-DGAMESPROUT_ORM_TEXTURE_REGISTER=t{slot}",
                            f"-DGAMESPROUT_ORM_SAMPLER_REGISTER=s{slot}",
                            f"-DGAMESPROUT_TRANSMISSION_TEXTURE_REGISTER=t{slot + 1}",
                            f"-DGAMESPROUT_TRANSMISSION_SAMPLER_REGISTER=s{slot + 1}"]
            run(command)
            reflection = root / (entry + ".json")
            run([options.shadercross, spirv, "-s", "SPIRV", "-d", "JSON", "-t", stage, "-e", entry, "-o", reflection])
            resources = json.loads(reflection.read_text())
            if entry in mapped_lit and (resources["samplers"] != mapped_lit[entry] + 2
                                        or resources["uniform_buffers"] != 4
                                        or resources["storage_buffers"] != 0):
                raise RuntimeError("Mapped Lit has an unexpected sampler or uniform layout: " + entry)
            declarations.append("inline constexpr unsigned " + entry + "Samplers = " + str(resources["samplers"]) + ";")
            declarations.append("inline constexpr unsigned " + entry + "Uniforms = " + str(resources["uniform_buffers"]) + ";")
            declarations.append("inline constexpr unsigned " + entry + "StorageBuffers = " + str(resources["storage_buffers"]) + ";")
            for format in ["SPIRV", "MSL", "DXIL"]:
                output = root / (entry + "." + format.lower())
                if format == "SPIRV":
                    data = spirv.read_bytes()
                    function = entry
                else:
                    command = [options.shadercross, spirv, "-s", "SPIRV", "-d", format, "-t", stage, "-e", entry, "-o", output]
                    if format == "MSL":
                        command += ["--msl-version", "2.1.0"]
                    run(command)
                    data = output.read_bytes()
                    function = entry
                    if format == "MSL":
                        match = re.search(r"\b" + stage + r"\s+\w+\s+(\w+)\s*\(", data.decode("utf-8"))
                        if not match:
                            raise RuntimeError("Cannot find generated Metal entry for " + entry)
                        function = match.group(1)
                        data += b"\0"
                name = entry + format
                declarations.append("alignas(4) inline constexpr unsigned char " + name + "[] = {")
                for start in range(0, len(data), 24):
                    declarations.append("    " + ",".join(str(value) for value in data[start:start + 24]) + ",")
                declarations.append("};")
                declarations.append("inline constexpr const char* " + name + "Entry = " + json.dumps(function) + ";")
    declarations.append("}")
    options.output.write_text("\n".join(declarations) + "\n")


if __name__ == "__main__":
    main()
